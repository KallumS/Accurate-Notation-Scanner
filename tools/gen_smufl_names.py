#!/usr/bin/env python3
"""Writes Source/Core/SmuflNames.inc from SMuFL's glyphnames.json.

    python3 tools/gen_smufl_names.py path/to/glyphnames.json

glyphnames.json is published with the SMuFL specification:
https://github.com/w3c/smufl/blob/gh-pages/metadata/glyphnames.json
"""
import json, os, sys

src = sys.argv[1]
names = json.load(open(src))
rows = sorted((int(v["codepoint"][2:], 16), k) for k, v in names.items())
out = os.path.join(os.path.dirname(__file__), "..", "Source", "Core", "SmuflNames.inc")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_smufl_names.py from SMuFL's glyphnames.json. Do not edit.\n")
    f.write("// SMuFL: (c) W3C Music Notation Community Group, W3C Community Final Specification Agreement.\n")
    for cp, name in rows:
        f.write('{ 0x%04X, "%s" },\n' % (cp, name))
print(len(rows), "names ->", out)
