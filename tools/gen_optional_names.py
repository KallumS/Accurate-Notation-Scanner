#!/usr/bin/env python3
"""Writes Source/Core/SmuflOptional.inc: the optional glyphs (stylistic
alternates, oversized noteheads...) that SMuFL fonts place at their own code
points in U+F400-U+F8FF, by font. Read from the fonts' metadata as packaged
with Verovio (pip install verovio):

    python3 tools/gen_optional_names.py
"""
import os, re, verovio
data = os.path.join(os.path.dirname(verovio.__file__), "data")
out = os.path.join(os.path.dirname(__file__), "..", "Source", "Core", "SmuflOptional.inc")
rows = []
for font in ("Bravura", "Leland", "Petaluma"):
    text = open(os.path.join(data, font + ".xml"), encoding="utf-8").read()
    for cp, name in re.findall(r'<g c="(F[0-9A-F]{3})"[^>]*n="([^"]+)"', text):
        rows.append((font, int(cp, 16), name))
with open(out, "w") as f:
    f.write("// Generated by tools/gen_optional_names.py from the fonts' SMuFL metadata. Do not edit.\n")
    for font, cp, name in sorted(rows):
        f.write('{ "%s", 0x%04X, "%s" },\n' % (font.lower(), cp, name))
print(len(rows), "optional glyphs ->", out)
