#!/usr/bin/env python3
"""Writes ScaleView Pro's own chord tests as C++ cases for Tests/TestChords.cpp.

Reads tests/test_scaleview_pro.lua from a checkout of KallumS/ScaleView-for-Reaper
and keeps every expect({notes}, "name") with the scale chosen when it runs. The
expected names are ScaleView's, untouched: the port must give the same.

    python3 tools/scaleview_cases.py path/to/test_scaleview_pro.lua > Tests/ScaleViewCases.inc
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()
env = {"C3": 48, "C4": 60}
scale = None
simplified = False   # ScaleView's "Simplify Note Names" option: not part of the port
out = []
for line in src.splitlines():
    if re.match(r'\s*simplify\(\)', line) or re.match(r'\s*chooseOption\("Simplify Note Names"\)', line):
        simplified = not simplified
        continue
    m = re.match(r'\s*chooseScale\("([^"]*)"\)', line)
    if m:
        s = m.group(1)
        if s == "Clear Scale":
            scale = None
        else:
            root, _, name = s.partition(" ")
            scale = (root, name)
        continue
    m = re.match(r'\s*expect\(\{([^}]*)\},\s*"([^"]*)"', line)
    if not m or simplified:
        continue
    try:
        notes = [int(eval(x.strip(), {}, env)) for x in m.group(1).split(",") if x.strip()]
    except Exception:
        continue
    root, name = scale if scale else ("", "")
    out.append('{ { %s }, "%s", "%s", "%s" },' % (", ".join(map(str, notes)), root, name, m.group(2)))
print("// Generated by tools/scaleview_cases.py from ScaleView Pro's tests/test_scaleview_pro.lua.")
print("// notes, key root, scale, the name ScaleView expects")
print("\n".join(out))
